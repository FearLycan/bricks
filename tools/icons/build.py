#!/usr/bin/env python3
"""
Build the self-hosted Phosphor icon subset used by the frontend.

Scans frontend/ and common/ for Phosphor classes (`ph ph-name`,
`ph-fill ph-name`, `ph-duotone ph-name`), cuts only those glyphs out of the
full Phosphor web fonts and writes:

  frontend/web/fonts/phosphor/Phosphor{,-Fill,-Duotone}.woff2
  frontend/web/css/icons.css

Run after adding a new icon anywhere in the code:

  npm install --prefix /tmp/phosphor @phosphor-icons/web
  pip install fonttools brotli
  python3 tools/icons/build.py /tmp/phosphor/node_modules/@phosphor-icons/web/src

Icons: Phosphor Icons (https://phosphoricons.com), MIT licence.
"""
import hashlib
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SRC = Path(sys.argv[1]) if len(sys.argv) > 1 else None
WEIGHTS = {
    # class, font family, source dir, file
    'regular': ('ph', 'Phosphor', 'regular', 'Phosphor'),
    'fill': ('ph-fill', 'Phosphor-Fill', 'fill', 'Phosphor-Fill'),
    'duotone': ('ph-duotone', 'Phosphor-Duotone', 'duotone', 'Phosphor-Duotone'),
}
NOT_ICONS = {'fill', 'duotone'}


def used_icons() -> dict[str, set[str]]:
    used = {w: set() for w in WEIGHTS}
    pat = re.compile(r'(?<![\w-])(ph|ph-fill|ph-duotone)\s+ph-([a-z0-9-]+)')
    for path in list((ROOT / 'frontend').rglob('*')) + list((ROOT / 'common').rglob('*')):
        if path.suffix not in {'.php', '.js'} or '/assets/' in str(path) or '/runtime/' in str(path):
            continue
        for cls, name in pat.findall(path.read_text(errors='ignore')):
            weight = {'ph': 'regular', 'ph-fill': 'fill', 'ph-duotone': 'duotone'}[cls]
            used[weight].add(name)
    # A regular icon may be switched to fill by JS (wishlist, stars) and back.
    both = used['regular'] | used['fill']
    used['regular'] = used['fill'] = both - NOT_ICONS
    return used


def glyphs(css: str, cls: str, name: str) -> list[str]:
    out = []
    for part in ('before', 'after'):
        m = re.search(r'\.' + re.escape(cls) + r'\.ph-' + re.escape(name) + r':' + part + r'\s*\{\s*content:\s*"\\([0-9a-f]+)"', css)
        if m:
            out.append(m.group(1))
    if not out:
        sys.exit(f'Unknown Phosphor icon: {cls} ph-{name}')
    return out


def main() -> None:
    if SRC is None or not SRC.is_dir():
        sys.exit(__doc__)
    used = used_icons()
    fonts_dir = ROOT / 'frontend/web/fonts/phosphor'
    fonts_dir.mkdir(parents=True, exist_ok=True)
    css_out = [
        '/* Generated by tools/icons/build.py - do not edit by hand.',
        '   Phosphor Icons (phosphoricons.com), MIT licence. Subset to the icons used on the site. */',
    ]
    rules = []
    for weight, (cls, family, folder, file) in WEIGHTS.items():
        names = sorted(used[weight])
        if not names:
            continue
        css = (SRC / folder / 'style.css').read_text()
        codepoints = set()
        for name in names:
            cps = glyphs(css, cls, name)
            codepoints.update(cps)
            if weight == 'duotone':
                rules.append(f'.ph-duotone.ph-{name}:before{{content:"\\{cps[0]}";opacity:.2}}'
                             f'.ph-duotone.ph-{name}:after{{content:"\\{cps[1]}";margin-left:-1em}}')
            else:
                rules.append(f'.{cls}.ph-{name}:before{{content:"\\{cps[0]}"}}')
        subprocess.run([
            sys.executable, '-m', 'fontTools.subset', str(SRC / folder / f'{file}.ttf'),
            '--unicodes=' + ','.join(f'U+{c}' for c in sorted(codepoints)),
            '--flavor=woff2', '--no-hinting', '--desubroutinize', '--layout-features=',
            f'--output-file={fonts_dir / (file + ".woff2")}',
        ], check=True)
        # Fonts are cached for a year (.htaccess): the content hash in the URL
        # makes browsers fetch a new subset when icons are added.
        digest = hashlib.sha1((fonts_dir / (file + '.woff2')).read_bytes()).hexdigest()[:10]
        css_out.append(
            f'@font-face{{font-family:"{family}";src:url("../fonts/phosphor/{file}.woff2?v={digest}") format("woff2");'
            f'font-weight:normal;font-style:normal;font-display:block}}'
            f'.{cls}{{font-family:"{family}"!important;speak:never;font-style:normal;font-weight:normal;'
            f'font-variant:normal;text-transform:none;line-height:1;display:inline-block;vertical-align:-.125em;'
            f'-webkit-font-smoothing:antialiased;-moz-osx-font-smoothing:grayscale}}'
        )
        print(f'{weight}: {len(names)} icons')
    css_out.extend(rules)
    (ROOT / 'frontend/web/css/icons.css').write_text('\n'.join(css_out) + '\n')


if __name__ == '__main__':
    main()
